/** Find a product by its URL slug */
export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

/** Get neighbouring products for prev/next navigation */
export function getAdjacentProducts(slug: string) {
  const idx = products.findIndex((p) => p.slug === slug);
  if (idx === -1) return { prev: undefined, next: undefined };
  return {
    prev: idx > 0 ? products[idx - 1] : products[products.length - 1],
    next: idx < products.length - 1 ? products[idx + 1] : products[0],
  };
}
